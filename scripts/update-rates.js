#!/usr/bin/env node
// Downloads the latest Bank of England quoted mortgage rates (2-year fixed, by
// loan-to-value) and writes data/rates.js. The BoE database doesn't allow
// browser requests, so the page loads this snapshot instead.
//
//   node scripts/update-rates.js
'use strict';

const fs = require('fs');
const path = require('path');

const SERIES = [
  { code: 'IUMZICQ', maxLtv: 60 },
  { code: 'IUMBV34', maxLtv: 75 },
  { code: 'IUMZICR', maxLtv: 85 },
  { code: 'IUMB482', maxLtv: 90 },
  { code: 'IUM2WTL', maxLtv: 95 },
];

function boeDate(d) {
  const m = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'][d.getUTCMonth()];
  return `${String(d.getUTCDate()).padStart(2, '0')}/${m}/${d.getUTCFullYear()}`;
}

async function main() {
  const from = new Date();
  from.setUTCMonth(from.getUTCMonth() - 6);
  const url = 'https://www.bankofengland.co.uk/boeapps/database/_iadb-fromshowcolumns.asp?csv.x=yes' +
    `&Datefrom=${boeDate(from)}&Dateto=now&SeriesCodes=${SERIES.map((s) => s.code).join(',')}` +
    '&CSVF=TN&UsingCodes=Y&VPD=Y&VFD=N';
  const res = await fetch(url, { headers: { 'User-Agent': 'Mozilla/5.0' } });
  if (!res.ok) throw new Error(`Bank of England returned ${res.status}`);
  const lines = (await res.text()).trim().split(/\r?\n/);
  const header = lines[0].split(',');
  if (header[0] !== 'DATE') throw new Error('Unexpected response:\n' + lines.slice(0, 3).join('\n'));

  // Latest month where every series has a value.
  for (let i = lines.length - 1; i > 0; i--) {
    const cells = lines[i].split(',');
    const bands = SERIES.map((s) => ({ maxLtv: s.maxLtv, rate: parseFloat(cells[header.indexOf(s.code)]) }));
    if (bands.some((b) => !Number.isFinite(b.rate))) continue;
    const data = {
      source: 'Bank of England, quoted household interest rates (2-year fixed)',
      url: 'https://www.bankofengland.co.uk/boeapps/database/',
      month: new Date(cells[0] + ' UTC').toISOString().slice(0, 7),
      bands,
    };
    const out = '// Generated by scripts/update-rates.js. Do not edit by hand.\n' +
      `(function (root) {\n  const rates = ${JSON.stringify(data, null, 2).replace(/\n/g, '\n  ')};\n` +
      "  if (typeof module !== 'undefined' && module.exports) module.exports = rates;\n" +
      '  else root.MORTGAGE_RATES = rates;\n' +
      "})(typeof globalThis !== 'undefined' ? globalThis : this);\n";
    fs.writeFileSync(path.join(__dirname, '..', 'data', 'rates.js'), out);
    console.log(`Rates for ${data.month}:`, bands.map((b) => `≤${b.maxLtv}% ${b.rate}%`).join(', '));
    return;
  }
  throw new Error('No complete month found in the response');
}

main().catch((e) => { console.error(e.message); process.exit(1); });
